#!/usr/bin/env python3
"""Audit the Unity package manifest and editor version against public metadata.

Why this exists
---------------
The environment this project is authored in has no route to
`packages.unity.com` or `unity.com`, so a pinned version cannot be verified
locally.  This script is executed by `.github/workflows/package-audit.yml`
(which does have internet access) and writes its findings into
`docs/reports/package-audit.{md,json}` so they can be read back from the
repository instead of from the (also unreachable) Actions log host.

It is also useful on a developer machine:

    python3 Tools/unity/audit_packages.py --markdown /tmp/audit.md
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REGISTRY = "https://packages.unity.com/"
ARCHIVE = "https://unity.com/releases/editor/archive"

# Packages that ship inside the Unity editor itself and are therefore not
# published on the public registry.  Pinning them is still required in
# Packages/manifest.json for a fresh project.
BUILT_IN = {"com.unity.ugui"}
BUILT_IN_PREFIX = ("com.unity.modules.",)


def curl(url: str, timeout: int = 45) -> str:
    try:
        res = subprocess.run(["curl", "-sL", "-m", str(timeout), url],
                             capture_output=True, text=True)
        return res.stdout or ""
    except Exception as exc:  # pragma: no cover - network dependent
        print(f"curl failed for {url}: {exc}", file=sys.stderr)
        return ""


def is_built_in(pkg: str) -> bool:
    return pkg in BUILT_IN or pkg.startswith(BUILT_IN_PREFIX)


def version_key(v: str):
    parts = re.split(r"[.\-]", v)
    out = []
    for p in parts:
        out.append((0, int(p)) if p.isdigit() else (1, p))
    return out


def editor_versions() -> dict:
    body = curl(ARCHIVE, 90)
    found = set(re.findall(r"\b(6000\.0\.\d+f\d+)\b", body))
    found |= set(re.findall(r"\b(2022\.3\.\d+f\d+)\b", body))
    lts6 = sorted((v for v in found if v.startswith("6000.0.")),
                  key=lambda s: [int(x) for x in re.findall(r"\d+", s)])
    lts22 = sorted((v for v in found if v.startswith("2022.3.")),
                   key=lambda s: [int(x) for x in re.findall(r"\d+", s)])
    return {"unity6_lts": lts6, "unity2022_lts": lts22, "raw_hits": len(found)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default="Packages/manifest.json")
    ap.add_argument("--project-version", default="ProjectSettings/ProjectVersion.txt")
    ap.add_argument("--markdown", default="docs/reports/package-audit.md")
    ap.add_argument("--json", default="docs/reports/package-audit.json")
    args = ap.parse_args()

    manifest = json.loads(Path(args.manifest).read_text())
    deps: dict[str, str] = manifest.get("dependencies", {})
    pv_text = Path(args.project_version).read_text().strip()
    editor_version = pv_text.split(":", 1)[1].strip().splitlines()[0] if ":" in pv_text else pv_text

    report = {
        "editor_version_pinned": editor_version,
        "packages": {},
        "failures": [],
    }
    rows = []

    for pkg, pinned in sorted(deps.items()):
        entry = {"pinned": pinned}
        if is_built_in(pkg):
            entry["status"] = "built-in (shipped with the editor, not on the public registry)"
            rows.append((pkg, pinned, entry["status"]))
            report["packages"][pkg] = entry
            continue

        body = curl(REGISTRY + pkg)
        try:
            data = json.loads(body)
        except Exception:
            entry["status"] = "REGISTRY UNREACHABLE OR PACKAGE NOT FOUND"
            rows.append((pkg, pinned, entry["status"]))
            report["packages"][pkg] = entry
            report["failures"].append(pkg)
            continue

        versions = list(data.get("versions", {}).keys())
        entry["available_tail"] = versions[-14:]
        entry["dist_tags"] = data.get("dist-tags", {})
        if pinned in versions:
            info = data["versions"][pinned]
            entry["status"] = "OK"
            entry["requires_unity"] = info.get("unity")
            entry["requires_unity_release"] = info.get("unityRelease")
            entry["dependencies"] = info.get("dependencies", {})
            rows.append((pkg, pinned, "OK - requires Unity %s%s, latest=%s" % (
                info.get("unity"), info.get("unityRelease") or "",
                data.get("dist-tags", {}).get("latest"))))
        else:
            entry["status"] = "MISSING"
            rows.append((pkg, pinned, "MISSING - available: " + ", ".join(versions[-14:])))
            report["failures"].append(pkg)
        report["packages"][pkg] = entry

    report["editor_releases"] = editor_versions()

    md = ["# Unity package / editor version audit", "",
          "Generated by `Tools/unity/audit_packages.py` via "
          "`.github/workflows/package-audit.yml`.", "",
          f"`ProjectSettings/ProjectVersion.txt` -> **{editor_version}**", "",
          "| package | pinned | status |", "| --- | --- | --- |"]
    for pkg, pinned, status in rows:
        md.append(f"| `{pkg}` | `{pinned}` | {status} |")
    md.append("")
    if report["failures"]:
        md.append("## FAILURES")
        for f in report["failures"]:
            md.append(f"- {f}")
    else:
        md.append("All pinned versions resolve.")
    md.append("")
    md.append("## Editor releases seen on unity.com/releases/editor/archive")
    md.append("")
    if report["editor_releases"]["unity6_lts"]:
        tail = report["editor_releases"]["unity6_lts"][-8:]
        md.append(f"- newest Unity 6 LTS patches: {', '.join(tail)}")
        md.append(f"- pinned `{editor_version}` listed: "
                  f"{'YES' if editor_version in report['editor_releases']['unity6_lts'] else 'NO'}")
    else:
        md.append("- archive page did not expose version strings (JS driven?)")
    if report["editor_releases"]["unity2022_lts"]:
        md.append(f"- newest 2022.3 LTS patches: "
                  f"{', '.join(report['editor_releases']['unity2022_lts'][-5:])}")
    md.append("")

    Path(args.markdown).parent.mkdir(parents=True, exist_ok=True)
    Path(args.markdown).write_text("\n".join(md) + "\n")
    Path(args.json).parent.mkdir(parents=True, exist_ok=True)
    Path(args.json).write_text(json.dumps(report, indent=2) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
